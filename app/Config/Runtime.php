<?php

declare(strict_types=1);

/**
 * Рантайм. Обычный PHP (FPM, php -S) ничего отсюда не читает: настройки применяются
 * только при запуске долгоживущего сервера (`php cli serve --swoole`).
 */
return [

    'swoole' => [

        # process: master раздаёт соединения воркерам (нужен для task workers).
        # base:    воркеры сами принимают соединения: меньше накладных расходов на коротких запросах.
        'mode' => env('SWOOLE_MODE', 'process'),

        # Очередь ожидающих соединений.
        'backlog' => (int) env('SWOOLE_BACKLOG', 2048),

        # Число воркеров. null = число ядер процессора (опция --workers перекрывает).
        'workers' => env('SWOOLE_WORKERS'),

        # Воркер перезапускается после стольких запросов: защита от утечек памяти.
        'max_request' => (int) env('SWOOLE_MAX_REQUEST', 5000),

        # Graceful shutdown: сколько секунд воркер дорабатывает запросы при остановке.
        'max_wait_time' => (int) env('SWOOLE_MAX_WAIT_TIME', 30),

        # Максимальное время обработки одного запроса, секунды. Дольше: клиент получает 504,
        # корутина запроса отменяется (ресурсы возвращаются в пул). 0 = без ограничения.
        # Отмена срабатывает, когда запрос ждёт ввод-вывод; чистый CPU-цикл прервать нельзя.
        'request_timeout' => (float) env('SWOOLE_REQUEST_TIMEOUT', 30),

        # Task workers: отдельные процессы для фоновых задач (TaskDispatcher::dispatch).
        # 0 = процессов нет, задачи выполняются в корутинах воркера.
        'task_workers' => (int) env('SWOOLE_TASK_WORKERS', 0),

        # Task worker перезапускается после стольких задач.
        'task_max_request' => (int) env('SWOOLE_TASK_MAX_REQUEST', 1000),

        # Корутинные хуки ввода-вывода (SWOOLE_HOOK_*).
        #   null  безопасный набор: всё, кроме файловых операций и sqlite (рекомендуется)
        #   0     хуки выключены: ввод-вывод блокирует воркер, конкурентность между запросами исчезает
        #   int   свой набор флагов
        'hook_flags' => null,
    ],

];
